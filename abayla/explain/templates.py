def _i(lang: str) -> int:
    return 0 if lang == "ru" else 1


@dataclass
class Explanation:
    title: str
    reason: str
    action: str
    notes: list[str] = field(default_factory=list)
    source: str = "template"
    level: str = ""

    def render(self, lang: str) -> str:
        t = TXT[lang]
        if self.level == "low":
            body = f"{self.title}\n{self.reason}"
        else:
            body = f"{self.title}\n{t['why']} {self.reason}"
        body += f"\n{t['do']} {self.action}"
        if self.notes:
            body += "\n\n" + "\n".join(self.notes)
        return body


def join_signals(signals: list[str], lang: str, limit: int = 3) -> str:
    parts = [SIGNAL_TEXT[s][_i(lang)] for s in signals[:limit]]
    if len(parts) <= 1:
        return "".join(parts)
    return ", ".join(parts[:-1]) + TXT[lang]["and"] + parts[-1]


def pick_action(level: str, signals: list[str], lang: str) -> str:
    if level in ("high", "uncertain"):
        for s in ACTION_PRIORITY:
            if s in signals:
                return ACTIONS[s][_i(lang)]
    return DEFAULT_ACTION[level][_i(lang)]


def template_explanation(analysis, lang: str) -> Explanation:
    """analysis — abayla.service.analyzer.Analysis."""
    lang = lang if lang in TXT else "ru"
    t = TXT[lang]
    risk = analysis.risk_signals
    if analysis.level == "high":
        reason = t["high_reason"].format(signals=join_signals(risk, lang)) if risk else t["high_model_only"]
    elif analysis.level == "uncertain":
        reason = t["uncertain_reason"].format(signals=join_signals(risk, lang)) if risk else t["uncertain_model_only"]
    else:
        reason = t["low_reason"]
    notes = []
    if analysis.overridden and analysis.override_reason == "strong_signal":
        notes.append(t["note_override"])
    if "code_notification" in analysis.signals and analysis.level == "low":
        notes.append(t["note_code"])
    if analysis.url_reports and "suspicious_link" not in analysis.signals:
        notes.append(t["note_link"])
    if analysis.truncated:
        notes.append(t["truncated"])
    if analysis.demo:
        notes.append(t["demo"])
    return Explanation(title=LEVEL_TITLE[lang][analysis.level], reason=reason,
                       action=pick_action(analysis.level, risk, lang), notes=notes,
                       level=analysis.level)
