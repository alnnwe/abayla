def t(lang: str, key: str, **kw) -> str:
    lang = lang if lang in T else "ru"
    s = T[lang].get(key) or T["ru"][key]
    return s.format(**kw) if kw else s


def all_variants(key: str) -> set[str]:
    """Тексты кнопки на обоих языках — чтобы кнопка работала независимо от выбранного языка."""
    return {T[lang][key] for lang in T}
