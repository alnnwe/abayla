def build_demo_dataframe() -> pd.DataFrame:
    rows = []
    n = 0
    for gi, grp in enumerate(GROUPS, start=1):
        group_id = f"demo_g{gi:03d}"
        for lang_key, language in (("ru", "ru"), ("kk", "kk"), ("ru2", "ru"), ("mixed", "mixed")):
            text = grp[lang_key]
            if not text:
                continue
            n += 1
            rows.append(
                {
                    "id": f"demo_{n:04d}",
                    "text": text,
                    "label": grp["label"],
                    "scheme": grp["scheme"],
                    "language": language,
                    "source_type": "synthetic_demo",
                    "source_id": DATA_VERSION,
                    "template_group": group_id,
                    "annotation_status": grp["status"],
                }
            )
    return pd.DataFrame(rows, columns=COLUMNS)


def write_demo_csv(path: str | Path) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    build_demo_dataframe().to_csv(path, index=False)
    return path


